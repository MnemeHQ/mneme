"""Shared fixtures for the OpenCode S1 bridge tests.

Fixture memories are generated by the canonical CLI so decision identity,
version identity and rule lineage are real, not hand-authored.
"""

from __future__ import annotations

import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

ADR_SOURCE = """---
id: ADR-001
title: "Storage adapter boundary"
status: accepted
priority: foundational
date: 2026-11-17
scope: storage.handlers
---

# ADR-001: Storage adapter boundary

## Context
Handlers must not import database drivers directly.

## Decision
Handlers use the project storage adapter.

## Constraints
- FORBID_LITERAL:
    value: psycopg2
    include_paths:
      - "src/handlers/**"
"""

TWO_RULE_ADR_SOURCE = """---
id: ADR-001
title: "Two literal rules"
status: accepted
priority: foundational
date: 2026-11-17
scope: storage.handlers
---

# ADR-001: Two literal rules

## Context
The fixture needs two independently attributable literal rules.

## Decision
Both literals are forbidden under the handler scope.

## Constraints
- FORBID_LITERAL:
    value: psycopg2
    include_paths:
      - "src/handlers/**"
- FORBID_LITERAL:
    value: forbidden_secondary
    include_paths:
      - "src/handlers/**"
"""


@dataclass(frozen=True)
class S1Fixture:
    root: Path
    memory: Path
    authority: Path
    decision_id: str
    version_id: str
    rule_id: str
    rule_value: str
    rule_scope: str
    rule_ids: dict[str, str]


def _run_cli(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "mneme", *args],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )


def _build_project(
    root: Path, sources: list[tuple[str, str]]
) -> S1Fixture:
    adr_dir = root / "adr"
    adr_dir.mkdir(parents=True, exist_ok=True)
    for filename, source in sources:
        (adr_dir / filename).write_text(source, encoding="utf-8", newline="\n")
    (root / "src" / "handlers").mkdir(parents=True, exist_ok=True)

    memory = root / ".mneme" / "project_memory.json"
    memory.parent.mkdir(parents=True, exist_ok=True)

    init = _run_cli(["init", "--path", str(memory)], root)
    assert init.returncode == 0, init.stderr

    imported = _run_cli(
        ["adr", "import", str(adr_dir), "--memory", str(memory), "--apply"],
        root,
    )
    assert imported.returncode == 0, imported.stderr

    data = json.loads(memory.read_text(encoding="utf-8"))
    index = data["decision_index"]
    rules = {rule["rule_payload"]["value"]: rule for rule in index["rules"]}
    primary = rules["psycopg2"]
    authority = {
        "decision_id": primary["decision_id"],
        "decision_version_id": primary["decision_version_id"],
        "rule_id": primary["rule_id"],
        "rule_value": primary["rule_payload"]["value"],
        "rule_scope": primary["applicability"]["include_paths"][0],
    }
    authority_path = root / "authority.json"
    authority_path.write_text(
        json.dumps(authority, indent=2) + "\n", encoding="utf-8", newline="\n"
    )

    return S1Fixture(
        root=root,
        memory=memory,
        authority=authority_path,
        decision_id=authority["decision_id"],
        version_id=authority["decision_version_id"],
        rule_id=authority["rule_id"],
        rule_value=authority["rule_value"],
        rule_scope=authority["rule_scope"],
        rule_ids={value: rule["rule_id"] for value, rule in rules.items()},
    )


@pytest.fixture
def s1_fixture(tmp_path: Path) -> S1Fixture:
    return _build_project(tmp_path, [("ADR-001-storage.md", ADR_SOURCE)])


@pytest.fixture
def two_rule_fixture(tmp_path: Path) -> S1Fixture:
    return _build_project(
        tmp_path / "two-rule", [("ADR-001-two-rules.md", TWO_RULE_ADR_SOURCE)]
    )


@pytest.fixture
def project_factory(tmp_path: Path):
    """Build an independent project; used for target-anchored sibling tests."""
    counter = iter(range(1, 100))

    def make(sources: list[tuple[str, str]] | None = None) -> S1Fixture:
        selected = sources or [("ADR-001-storage.md", ADR_SOURCE)]
        return _build_project(tmp_path / f"project-{next(counter)}", selected)

    return make

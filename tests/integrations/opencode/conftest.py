"""Shared fixture for the OpenCode S1 bridge tests.

The fixture memory is generated by the canonical CLI so the decision identity,
version identity and rule lineage are real, not hand-authored.
"""

from __future__ import annotations

import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

ADR_SOURCE = """---
id: ADR-001
title: "Storage adapter boundary"
status: accepted
priority: foundational
date: 2026-11-17
scope: storage.handlers
---

# ADR-001: Storage adapter boundary

## Context
Handlers must not import database drivers directly.

## Decision
Handlers use the project storage adapter.

## Constraints
- FORBID_LITERAL:
    value: psycopg2
    include_paths:
      - "src/handlers/**"
"""


@dataclass(frozen=True)
class S1Fixture:
    root: Path
    memory: Path
    authority: Path
    decision_id: str
    version_id: str
    rule_id: str
    rule_value: str
    rule_scope: str


def _run_cli(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "mneme", *args],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )


@pytest.fixture
def s1_fixture(tmp_path: Path) -> S1Fixture:
    adr_dir = tmp_path / "adr"
    adr_dir.mkdir()
    (adr_dir / "ADR-001-storage.md").write_text(
        ADR_SOURCE, encoding="utf-8", newline="\n"
    )
    (tmp_path / "src" / "handlers").mkdir(parents=True)

    memory = tmp_path / ".mneme" / "project_memory.json"
    memory.parent.mkdir(parents=True)

    init = _run_cli(["init", "--path", str(memory)], tmp_path)
    assert init.returncode == 0, init.stderr

    imported = _run_cli(
        ["adr", "import", str(adr_dir), "--memory", str(memory), "--apply"],
        tmp_path,
    )
    assert imported.returncode == 0, imported.stderr

    data = json.loads(memory.read_text(encoding="utf-8"))
    index = data["decision_index"]
    decision = index["decisions"][0]
    rule = index["rules"][0]
    authority = {
        "decision_id": decision["decision_id"],
        "decision_version_id": decision["active_version_id"],
        "rule_id": rule["rule_id"],
        "rule_value": rule["rule_payload"]["value"],
        "rule_scope": rule["applicability"]["include_paths"][0],
    }
    authority_path = tmp_path / "authority.json"
    authority_path.write_text(
        json.dumps(authority, indent=2) + "\n", encoding="utf-8", newline="\n"
    )

    return S1Fixture(
        root=tmp_path,
        memory=memory,
        authority=authority_path,
        decision_id=authority["decision_id"],
        version_id=authority["decision_version_id"],
        rule_id=authority["rule_id"],
        rule_value=authority["rule_value"],
        rule_scope=authority["rule_scope"],
    )
